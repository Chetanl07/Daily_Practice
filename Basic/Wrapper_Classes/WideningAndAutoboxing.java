public class WideningAndAutoboxing {
    public static void main(String[] args) {
        long a=12;       //  widening 
        System.out.println(a);

        Integer b= 15;   // autoboxing
        System.out.println(b);

        Long c=20L;
        System.out.println(c);

        Float d=12f;
        System.out.println(d);

        Double e= 90D;
        System.out.println(e);
    }
    
}
