public class Concate {
    public static void main(String []args)
    {
        String s1="Data";
        String s2="base";

        String s3=s1.concat(s2);
        System.out.println(s3);  // Database

        String s4="James ";
        String s5="Gosling";
        String s6=s4+s5;
        System.out.println(s6); // James Gosling

        String s7="Naresh";
        System.out.println(s7.concat(" technology")); // Naresh technology


    }
}
